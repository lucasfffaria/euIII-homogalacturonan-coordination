"""Check of the rigid Eu-O scans of Sparkle/RM1 (Table 2, Table S3c, Figure 3) against the MOPAC outputs of the package.

data/scans_semiempirical_v2.json holds the heats of formation of the rigid scans of the four models.  The scans of
Sparkle/PM7 as distributed, Sparkle/PM7+EuO and RM1 are regenerated by semi_scans.py (which runs MOPAC); those of Sparkle/RM1
were run as single points in revision/R4_sparkle_rm1_scans (Eu3+ and the six rigid ligands) and
revision/R4b_sparkle_rm1_scans (132 scan points).  This script reads the final heat of formation of each of those outputs
and compares it with the archived value.

Usage (from code/):  python check_scans.py [--sm ..]      Needs numpy.
"""
import argparse, json, os, re
import numpy as np

here = os.path.dirname(os.path.abspath(__file__)); ap = argparse.ArgumentParser(); ap.add_argument("--sm", default=os.path.join(here, "..")); a = ap.parse_args()
sc = json.load(open(os.path.join(a.sm, "data", "scans_semiempirical_v2.json"))); r = sc["r"]; d = sc["Sparkle/RM1"]


def heat(stage, job):
    t = open(os.path.join(a.sm, "revision", stage, job, job + ".out"), errors="ignore").read()
    return float(re.findall(r"FINAL HEAT OF FORMATION\s*=\s*([-\d.]+)\s*KCAL/MOL", t)[-1])


dev = [abs(heat("R4_sparkle_rm1_scans", "SRM1_Eu") - d["Eu3+"])]; n = 1
for lig in ("water", "methanol", "methoxide", "acetate", "ether", "ester"):
    dev.append(abs(heat("R4_sparkle_rm1_scans", f"SRM1_{lig}_lig") - d[lig + "_ligand"])); n += 1
    for ri, h in zip(r, d[lig]):
        dev.append(abs(heat("R4b_sparkle_rm1_scans", f"SRM1_{lig}_d{round(ri * 10):d}") - h)); n += 1
print(f"{n} single points of Sparkle/RM1 read; largest deviation from data/scans_semiempirical_v2.json: {max(dev):.5f} kcal/mol")
